import fs from 'node:fs';
import crypto from 'node:crypto';
const origin=process.argv[2],url=new URL(origin);
if(url.protocol!=='https:'||!(url.hostname==='plataforma-ensino-chi.vercel.app'||/^plataforma-ensino-[a-z0-9]+-andrea-francas-projects\.vercel\.app$/.test(url.hostname)))throw Error('Destino inesperado');
const root='test-results/content-workspace',sha=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
const localHtml=fs.readFileSync(root+'/frontend/dist/index.html','utf8'),entry=localHtml.match(/src="([^"\s]+\.js)"/)[1];
const html=await fetch(origin).then(r=>{if(!r.ok)throw Error('Frontend inacessível');return r.text();});
if(!html.includes(entry))throw Error('Entrada diferente do build aprovado');
const bytes=Buffer.from(await fetch(origin+entry).then(r=>r.arrayBuffer()));
if(sha(bytes)!==sha(fs.readFileSync(root+'/frontend/dist'+entry)))throw Error('Bundle diferente do build local');
const js=bytes.toString('utf8');
if(!js.includes('https://gnyiyhnbpjhdgrhsevbh.supabase.co'))throw Error('Supabase divergente');
const editorChunk=js.match(/LessonEditor-[A-Za-z0-9_-]+\.js/)[0];
const editor=await fetch(origin+'/assets/'+editorChunk).then(r=>r.text());
const chunk=editor.match(/UnifiedLessonImporter-[A-Za-z0-9_-]+\.js/)[0];
const importer=await fetch(origin+'/assets/'+chunk).then(r=>r.text());
if(!importer.includes('Importar ZIP da aula')||!importer.includes('Não envie o Kit Work.'))throw Error('Melhoria visual ausente');
const result={origin,passed:true,entry,entrySha256:sha(bytes),supabaseProject:'gnyiyhnbpjhdgrhsevbh',uploadButtonPresent:true,sameBuildAsLocal:true};
fs.writeFileSync(root+'/'+(url.hostname==='plataforma-ensino-chi.vercel.app'?'import-button-production.json':'import-button-candidate.json'),JSON.stringify(result,null,2));
console.log(JSON.stringify(result));
