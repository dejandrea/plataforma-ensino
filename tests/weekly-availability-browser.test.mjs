import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {createServer} from 'vite';
import {chromium} from '@playwright/test';

test('real agenda editor: per-day ranges, explicit copy, validation and saved reload on desktop/mobile',{timeout:180000},async t=>{
  const server=await createServer({logLevel:'error',plugins:[{name:'synthetic-weekly-client',enforce:'pre',load(id){if(id.replaceAll('\\','/').endsWith('/src/lib/supabaseClient.ts'))return 'export const supabase=new Proxy({}, {get:(_,key)=>window.syntheticClient[key]});';}}],server:{host:'127.0.0.1',port:0}});
  await server.listen();t.after(()=>server.close());const base=server.resolvedUrls.local[0];
  const browser=await chromium.launch({channel:process.platform==='win32'?'chrome':undefined,headless:true});t.after(()=>browser.close());
  const context=await browser.newContext({viewport:{width:1280,height:960}});const external=[],errors=[];
  await context.route('**/*',route=>{const u=new URL(route.request().url());if(u.hostname==='127.0.0.1')return route.continue();if(u.hostname==='fonts.googleapis.com')return route.fulfill({contentType:'text/css',body:''});external.push(u.origin);return route.abort();});
  const page=await context.newPage();page.setDefaultTimeout(60000);page.on('pageerror',e=>errors.push(e.message));page.on('dialog',dialog=>dialog.dismiss());
  await page.goto(base+'tests/fixtures/weekly-availability.html',{waitUntil:'domcontentloaded'});
  const open=()=>page.getByRole('button',{name:'Configurar Disponibilidade',exact:true}).click();
  await open();await page.getByLabel('Segunda-feira: início da faixa 1',{exact:true}).fill('14:00');
  await page.getByRole('button',{name:'Copiar horários de Segunda-feira',exact:true}).click();
  for(const label of ['Terça-feira','Quarta-feira','Quinta-feira','Sexta-feira'])await page.getByRole('checkbox',{name:label,exact:true}).check();
  await page.getByRole('button',{name:'Aplicar cópia'}).click();
  await page.getByRole('button',{name:'Adicionar faixa em Sábado',exact:true}).click();
  await page.getByLabel('Sábado: fim da faixa 1',{exact:true}).fill('09:00');
  await page.getByRole('button',{name:'Adicionar faixa em Sábado',exact:true}).click();
  await page.getByLabel('Sábado: início da faixa 2',{exact:true}).fill('14:00');
  await page.getByLabel('Sábado: fim da faixa 2',{exact:true}).fill('19:00');
  await page.getByRole('button',{name:'Adicionar faixa em Domingo',exact:true}).click();
  await page.getByRole('button',{name:'Remover faixa 1 de Domingo',exact:true}).click();
  await page.getByLabel('Segunda-feira: início da faixa 1',{exact:true}).fill('06:00');
  await page.getByRole('button',{name:'Salvar disponibilidade',exact:true}).click();
  assert.equal(await page.evaluate(()=>window.weeklyState.writes.length),0);assert.ok(await page.getByRole('alert').count());
  await page.getByLabel('Segunda-feira: início da faixa 1',{exact:true}).fill('14:00');
  await page.getByRole('button',{name:'Salvar disponibilidade',exact:true}).click();
  await page.waitForFunction(()=>window.weeklyState.writes.length===1);
  const settings=await page.evaluate(()=>window.weeklyState.settings);
  assert.deepEqual(settings.availability_weekdays,[1,2,3,4,5,6]);
  assert.deepEqual(settings.availability_weekly_intervals['6'],[{start:'07:00',end:'09:00'},{start:'14:00',end:'19:00'}]);
  assert.deepEqual(settings.availability_weekly_intervals['7'],[]);
  await page.reload({waitUntil:'domcontentloaded'});await open();
  assert.equal(await page.getByLabel('Segunda-feira: início da faixa 1',{exact:true}).inputValue(),'14:00');
  assert.equal(await page.getByLabel('Sábado: início da faixa 1',{exact:true}).inputValue(),'07:00');
  assert.equal(await page.getByLabel('Sábado: início da faixa 2',{exact:true}).inputValue(),'14:00');
  await mkdir('output/availability',{recursive:true});
  await page.getByRole('region',{name:'Horários por dia da semana'}).screenshot({path:'output/availability/horarios-semana-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  t.diagnostic(JSON.stringify(await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,overflow:Array.from(document.querySelectorAll('body *')).filter(el=>el.getBoundingClientRect().right>innerWidth+1).slice(0,8).map(el=>({tag:el.tagName,cls:el.className,right:el.getBoundingClientRect().right,text:el.textContent?.slice(0,70)}))}))));
  await page.screenshot({path:'output/availability/agenda-celular.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  const region=page.getByRole('region',{name:'Horários por dia da semana'});
  assert.equal(await region.evaluate(el=>el.scrollWidth<=el.clientWidth),true);
  // Capture all seven days at the actual mobile editor width, without the modal's scroll clipping.
  const preview=await region.evaluate(el=>({markup:el.outerHTML,width:el.clientWidth}));
  const styles=await page.locator('style').allTextContents();
  await page.setContent(`<style>${styles.join('\n')}</style><main style="width:${preview.width}px;margin:16px auto">${preview.markup}</main>`);
  await page.locator('main').screenshot({path:'output/availability/horarios-semana-celular.png'});
  assert.deepEqual(external,[]);assert.deepEqual(errors,[]);
});
