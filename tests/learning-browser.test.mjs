import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { id } from './fixtures/learning-test-db.mjs';
import { createLearningBrowser } from './fixtures/learning-browser-harness.mjs';

test('real lesson UI → local HTTP adapter → PostgreSQL RPC → saved feedback and curriculum', { timeout: 90000 },async t => {
  const {page,context,appUrl,query,requests,pageErrors,steps,loseResponse} = await createLearningBrowser(t);
  const open = async (lesson=15) => {
    await page.goto(`${appUrl}tests/fixtures/learning-browser.html?lesson=${id(lesson)}`,{waitUntil:'domcontentloaded'});
    await page.getByRole('heading',{name:lesson===15?'Minha primeira página HTML':lesson===24?'Prática acompanhada':'Aula antiga',exact:true}).waitFor();
  };
  await open();
  steps.push('initial snapshot rendered');
  const navigation = page.getByRole('navigation',{name:'Atividades da aula'});
  assert.equal(await page.getByRole('button',{name:'Concluir aula',exact:true}).isDisabled(),true);
  assert.equal(await page.getByRole('progressbar',{name:'Atividades obrigatórias concluídas'}).getAttribute('aria-valuenow'),'0');
  assert.equal(await page.getByRole('button',{name:/Miniprojeto/}).isDisabled(),true);
  assert.equal(await page.getByText('O que você vai aprender',{exact:true}).count(),1);
  const popupPromise = context.waitForEvent('page');
  await page.getByRole('link',{name:/Abrir material de estudo/}).click();
  const popup = await popupPromise; await popup.close();
  steps.push('external link opened');
  assert.equal((await query('select count(*) n from student_activity_progress')).rows[0].n,0);
  await page.getByRole('button',{name:'Confirmar estudo',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('[role=progressbar]')?.getAttribute('aria-valuenow')==='1');
  await page.reload(); await page.getByRole('heading',{name:'Minha primeira página HTML',exact:true}).waitFor();
  steps.push('study restored after reload');
  assert.equal(await page.getByRole('progressbar',{name:'Atividades obrigatórias concluídas'}).getAttribute('aria-valuenow'),'1');
  const quizToggle = navigation.locator('button[aria-controls="activity-panel-'+id(32)+'"]');
  await quizToggle.waitFor();
  if (await quizToggle.getAttribute('aria-expanded') !== 'true') await quizToggle.click();
  await page.getByRole('radio',{name:'head',exact:true}).check();
  await page.getByRole('button',{name:'Enviar respostas',exact:true}).click();
  await page.getByText('Continue praticando · 0/100',{exact:true}).waitFor();
  steps.push('failed quiz saved');
  await page.reload(); await page.getByText('Continue praticando · 0/100',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Tentar novamente',exact:true}).click();
  await page.getByRole('radio',{name:'body',exact:true}).check();
  loseResponse();
  await page.getByRole('button',{name:'Enviar respostas',exact:true}).click();
  // Chrome may transparently replay the dropped POST. Other browsers surface
  // an error: retrying the unchanged answers must use the same request ID.
  await page.waitForFunction(() => document.querySelector('[role=alert]') || document.body.textContent.includes('Questionário aprovado!'));
  if (await page.getByRole('alert').count()) await page.getByRole('button',{name:'Enviar respostas',exact:true}).click();
  steps.push('lost quiz response handled without a duplicate attempt');
  await page.getByText('Questionário aprovado! · 100/100',{exact:true}).waitFor();
  await page.getByRole('heading',{name:'Aula concluída',exact:true}).waitFor();
  assert.equal(await page.getByRole('progressbar',{name:'Atividades obrigatórias concluídas'}).getAttribute('aria-valuenow'),'2');
  assert.equal((await query('select count(*) n from quiz_attempts where activity_id=$1',[id(32)])).rows[0].n,2);
  assert.equal((await query("select count(*) n from student_xp_events where event_type='lesson' and active")).rows[0].n,1);
  const quizRequests = requests.filter(r => r.name==='submit_student_assessment');
  assert.equal(quizRequests.length,3);
  assert.equal(quizRequests[1].params.p_session_id,quizRequests[2].params.p_session_id);
  assert.equal(Object.hasOwn(quizRequests[0].params,'p_score'),false);
  await mkdir('test-results',{recursive:true});
  await page.waitForFunction(() => document.querySelector('main')?.getAttribute('aria-busy')==='false');
  await page.screenshot({path:'test-results/learning-desktop.png',fullPage:true,animations:'disabled'});
  await page.setViewportSize({width:390,height:844});
  await open(24);
  await page.getByRole('heading',{name:'Prepare-se para o encontro',exact:true}).waitFor();
  await page.getByRole('navigation').getByRole('button',{name:/Miniprojeto/}).click();
  await page.getByRole('heading',{name:'Requisitos',exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Confirmar estudo',exact:true}).count(),0);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth<=window.innerWidth),true);
  await page.screenshot({path:'test-results/learning-mobile.png',fullPage:true,animations:'disabled'});
  await open(28);
  assert.equal(await page.getByRole('navigation',{name:'Atividades da aula'}).count(),0);
  await page.getByRole('button',{name:'Concluir aula',exact:true}).click();
  await page.getByRole('heading',{name:'Aula concluída',exact:true}).waitFor();
  assert.deepEqual(pageErrors,[]);
});
