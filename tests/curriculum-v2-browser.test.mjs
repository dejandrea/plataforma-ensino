import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {createLearningBrowser} from './fixtures/learning-browser-harness.mjs';
import {curriculumManifest as m} from './fixtures/curriculum-db.mjs';
import {fixtureUsers,id} from './fixtures/learning-test-db.mjs';
const overflow=page=>page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
const open=async(app,query)=>app.page.goto(app.appUrl+'tests/fixtures/learning-browser.html?'+query,{waitUntil:'domcontentloaded',timeout:60000});

test('curriculum roadmap and pedagogical journey expose planned lessons, preserve the original learner and fit mobile',{timeout:150000},async t=>{
 const app=await createLearningBrowser(t,{curriculum:true});const {page}=app;app.setIdentity('admin');
 await mkdir('test-results',{recursive:true});
 await open(app,'mode=curriculum-cards');
 await page.getByRole('heading',{name:m.lessons.at(-1).title,exact:true}).waitFor();
 assert.equal(await page.locator('button:disabled').count(),13);
 assert.equal(await page.getByText('Introdução',{exact:true}).count(),1);
 assert.equal(await page.getByText('Aula 14',{exact:true}).count(),1);
 assert.equal(await overflow(page),false);
 await page.screenshot({path:'test-results/curriculum-v2-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});assert.equal(await overflow(page),false);
 await page.screenshot({path:'test-results/curriculum-v2-mobile.png',fullPage:true});
 await open(app,'mode=pedagogy&jornada='+fixtureUsers.other+'&curso='+m.courseId);
 await page.getByText('0/15 aulas',{exact:false}).waitFor();
 await page.locator('summary').filter({hasText:'HTML Básico'}).click();
 await page.locator('summary').filter({hasText:m.submodules[0].title}).click();
 await page.getByRole('heading',{name:m.lessons[0].title,exact:true}).waitFor();
 assert.equal(await page.getByText('Em preparação',{exact:true}).count(),13);
 assert.equal(await overflow(page),false);
 await page.screenshot({path:'test-results/curriculum-v2-journey-mobile.png',fullPage:true});
 app.setIdentity('teacher');
 await open(app,'mode=pedagogy&jornada='+fixtureUsers.student+'&curso='+m.courseId);
 await page.getByText('2/3 aulas concluídas',{exact:true}).waitFor();
 await page.locator('summary').filter({hasText:'HTML Básico'}).click();
 await page.locator('summary').filter({hasText:m.submodules[0].title}).click();
 assert.equal(await page.getByRole('heading',{name:m.lessons[0].title,exact:true}).count(),0);
 assert.equal(app.requests.some(r=>/complete_|publish_|submit_|review_/.test(r.name)),false);
 assert.deepEqual(app.pageErrors,[]);
});

test('admin release is explicit and validated; published material becomes available to new learners and earns official XP',{timeout:150000},async t=>{
 const app=await createLearningBrowser(t,{curriculum:true});const {page,query}=app;app.setIdentity('admin');
 const lesson=m.lessons[0];
 await open(app,'mode=curriculum-publication&lesson='+lesson.id);
 await page.getByRole('button',{name:'Liberar aula para alunos',exact:true}).waitFor();
 page.once('dialog',dialog=>dialog.dismiss());
 await page.getByRole('button',{name:'Liberar aula para alunos',exact:true}).click();
 assert.equal(app.requests.filter(r=>r.name==='publish_curriculum_lesson').length,0);
 page.once('dialog',dialog=>dialog.accept());
 await page.getByRole('button',{name:'Liberar aula para alunos',exact:true}).click();
 await page.getByRole('alert').filter({hasText:'Importe e valide'}).waitFor();
 await app.login('admin','postgres');
 await query("insert into lesson_activities(id,lesson_id,key,title,activity_type,order_index,is_required,content_json,gamification_json) select $1,$2,'browser-new-study','Material novo','slides',0,true,content_json,gamification_json from lesson_activities where id=$3",[id(9900),lesson.id,'111d3ae2-0ec0-4b58-9e4e-1b47d0798528']);
 await query("update lesson_activities set publication_status='published' where id=$1",[id(9900)]);
 page.once('dialog',dialog=>dialog.accept());
 await page.getByRole('button',{name:'Liberar aula para alunos',exact:true}).click();
 await page.getByText('Aula liberada',{exact:true}).waitFor();
 app.setIdentity('other');
 await open(app,'lesson='+lesson.id);
 await page.getByRole('heading',{name:lesson.title,exact:true}).waitFor();
 assert.equal(await page.getByRole('button',{name:'Concluir aula',exact:true}).isDisabled(),true);
 await page.getByRole('button',{name:'Confirmar estudo',exact:true}).click();
 await page.getByRole('button',{name:'Conclusão registrada',exact:true}).waitFor();
 await app.login('admin','postgres');
 assert.equal((await query("select points from student_xp_events where student_id=$1 and event_type='learning_activity' and source_id=$2",[fixtureUsers.other,id(9900)])).rows[0].points,10);
 assert.equal((await query("select points from student_xp_events where student_id=$1 and event_type='lesson' and source_id=$2",[fixtureUsers.other,lesson.id])).rows[0].points,50);
 app.setIdentity('student');await open(app,'lesson='+lesson.id);
 await page.getByText('Esta aula ainda nao esta liberada.',{exact:true}).waitFor();
 assert.deepEqual(app.pageErrors,[]);
});
